"""Fails if a tracked file (or a commit) looks like game data or a privacy leak. Needs no game data.
Usage: python -I scripts/repo_guard.py                    check the tracked tree
       python -I scripts/repo_guard.py --history [RANGE]  check every commit in RANGE (default: all of HEAD, e.g. origin/main..HEAD):
                                                          added lines, file names, blobs, author/committer identity, messages
       python -I scripts/repo_guard.py --selftest         prove every rule fires on fixtures (no repo needed beyond a temp one)"""
import re, subprocess, sys, os, tempfile

BAD_EXT = {".bin", ".cue", ".iso", ".chd", ".7z", ".zip", ".rar", ".rom", ".pbp", ".ecm", ".exe", ".dll", ".mcd", ".img", ".mdf", ".mds",
           ".ccd", ".sub", ".sav", ".state"}
BAD_DIR = (".beads/", ".claude/", ".codex/", ".agents/")
ALLOW_PATHS = set()  # explicit, minimal exceptions to the name rules (exact repo-relative paths); none needed today
BIOS_SIZE = 512 * 1024
BIOS_MD5 = {  # well-known retail BIOS dumps (md5 of the whole image)
    "924e392ed05558ffdb115408c263dccf", "8dd7d5296a650fac7319bce665a6a53c", "490f666e1afb15b7362b406ed1cea246",
    "32736f17079d0b2b7024407c39bd3050", "1e68c231d0896b7eadcad1d7d8e76129"}
BIOS_MARKS = (b"Sony Computer Entertainment", b"System ROM Version", b"SCPH-")
BIOS_RESET = b"\x13\x00\x08\x3c"  # R3000 BIOS reset vector at offset 0: lui t0,0x13 (SCPH images start with it)
GEN_PATH = re.compile(r"^recomp/(?:.*/)?_?gen[^/]*(?:/|\.(?:c|h|cc|cpp|inc)$)", re.I)
GEN_BANNER = re.compile(rb"(?i)(auto-?generated|generated by psxrecomp|psxrecomp generated|@generated|do not edit)")
C_EXT = (".c", ".h", ".cc", ".cpp", ".inc")
USERS = r"[^\\/\s'\"`<>*%$:;,)\]]+"
WINUSER = re.compile(r"[A-Za-z]:[\\/]+Users[\\/]+(" + USERS + ")", re.I)                # drive-letter forms
UNIXUSER = re.compile(r"(?<![\w.~-])/(?:[A-Za-z]/)?(?:Users|home)/(" + USERS + ")")      # git-bash, macOS and Linux forms
OK_USER = {"<home>", "public", "default", "all users", "<name>", "<user>", "username", "%username%", "$env", "user", "runner", "you",
           "me", "name", "yourname", "<you>"}
MAIL = re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+")
CTRL = re.compile(rb"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
# the only commit identities allowed in history (the project's GitHub noreply forms; see CONTRIBUTING.md)
OK_MAIL_END = ("@users.noreply.github.com", "noreply@anthropic.com")  # the latter is the Co-Authored-By trailer address
OK_NAMES = {"ZacheerKour"}
OK_EMAILS = {"344188240+zacheerkour@users.noreply.github.com", "zacheerkour@users.noreply.github.com"}


def name_problems(f):
    low = f.lower(); out = []
    if f in ALLOW_PATHS: return out
    if os.path.splitext(low)[1] in BAD_EXT: out.append("game-like binary extension")
    if low.startswith(BAD_DIR): out.append("internal tooling directory")
    if GEN_PATH.search(f): out.append("generated C under recomp/ (derived from game code)")
    return out


def bios_problem(data):
    import hashlib
    if hashlib.md5(data).hexdigest() in BIOS_MD5: return "known BIOS image"
    if len(data) == BIOS_SIZE and (data[:4] == BIOS_RESET or any(m in data for m in BIOS_MARKS)): return "512 KiB file with a PS1 BIOS signature"
    if len(data) >= 64 * 1024 and BIOS_MARKS[0] in data and BIOS_MARKS[1] in data: return "contains PS1 BIOS strings"


def text_problems(t):
    out = []
    for rx in (WINUSER, UNIXUSER):
        for m in rx.finditer(t):
            if m.group(1).lower() not in OK_USER: out.append("home path: " + m.group(0)[:40])
    for m in MAIL.finditer(t):
        if not m.group().lower().endswith(OK_MAIL_END): out.append("e-mail address: " + m.group())
    return out


def blob_problems(f, data):
    """Whole-file checks (name, size, content); f is the repo-relative path."""
    out = name_problems(f)
    if len(data) > 5 * 1024 * 1024: out.append("over 5 MB")
    b = bios_problem(data)
    if b: out.append(b)
    # vectors: synthetic binaries from tests/slz/gen_vectors.py, exempt from the control-character check
    if not f.startswith("tests/slz/vectors/") and CTRL.search(data): out.append("control character")
    if f.lower().endswith(C_EXT) and GEN_BANNER.search(data[:2048]): out.append("generator banner in C source")
    if b"\0" not in data[:8192]: out += text_problems(data.decode("utf-8", "replace"))
    return out


def identity_problems(label, name, email):
    out = []
    if email.lower() not in OK_EMAILS: out.append("%s e-mail not an allowed noreply identity: %s" % (label, email))
    if name not in OK_NAMES: out.append("%s name not allowed: %s" % (label, name))
    return out


def git(root, *a):
    return subprocess.check_output(["git", "-C", root] + list(a))


def history_problems(root, rng):
    """Every commit in rng (a rev or range): identities, message, file names, added blobs/lines. Returns [(commit, why)]."""
    bad = []
    for c in git(root, "rev-list", rng).decode().split():
        an, ae, cn, ce, msg = git(root, "log", "-1", "--format=%an%x00%ae%x00%cn%x00%ce%x00%B", c).decode("utf-8", "replace").split("\0", 4)
        for w in identity_problems("author", an, ae) + identity_problems("committer", cn, ce) + text_problems(msg):
            bad.append((c[:10], w))
        raw = git(root, "diff-tree", "-r", "--root", "--no-commit-id", "--raw", "--no-abbrev", "--diff-filter=AMR", c).decode("utf-8", "replace")
        for ln in raw.splitlines():
            meta, _, path = ln.partition("\t")
            sha = meta.split()[3]
            size = int(git(root, "cat-file", "-s", sha))
            for w in name_problems(path): bad.append((c[:10], path + ": " + w))
            if size > 5 * 1024 * 1024: bad.append((c[:10], path + ": over 5 MB"))
            if size == BIOS_SIZE or size >= 64 * 1024:
                b = bios_problem(git(root, "cat-file", "blob", sha))
                if b: bad.append((c[:10], path + ": " + b))
            if os.path.splitext(path.lower())[1] in C_EXT and size < 2 * 1024 * 1024 and GEN_BANNER.search(git(root, "cat-file", "blob", sha)[:2048]):
                bad.append((c[:10], path + ": generator banner in C source"))
        patch = git(root, "diff-tree", "-p", "-U0", "--root", "--no-commit-id", "--no-color", "--diff-filter=AMR", c).decode("utf-8", "replace")
        added = "\n".join(l[1:] for l in patch.splitlines() if l.startswith("+") and not l.startswith("+++"))
        for w in text_problems(added): bad.append((c[:10], "added line: " + w))
    return bad


def tree_problems(root):
    files = git(root, "ls-files", "-z").decode("utf-8").split("\0")[:-1]
    bad = []
    for f in files:
        p = os.path.join(root, f)
        if not os.path.isfile(p): continue
        with open(p, "rb") as h: data = h.read()
        for w in blob_problems(f, data): bad.append((f, w))
    return files, bad


def selftest():
    n = 0
    def expect(cond, what):
        nonlocal n
        if not cond: print("SELFTEST FAIL:", what); n += 1
    u, hm, at = "Users", "ho" + "me", "@"  # fixtures are assembled at run time so this file never contains a path the guard would flag
    for ext in sorted(BAD_EXT): expect(name_problems("x/a" + ext), "extension " + ext)
    expect(not name_problems("x/a.txt") and not name_problems("recomp/bios/gen_scph5501.ps1"), "clean names")
    expect(name_problems(".beads/x") and name_problems(".claude/x"), "tooling dirs")
    expect(name_problems("recomp/bios/_gen/generated/a.c") and name_problems("recomp/x/gen_tables.c") and not name_problems("src/gen_a.c"), "generated C path")
    expect(blob_problems("a.c", b"/* Generated by psxrecomp */\nint x;\n"), "generator banner")
    expect(not blob_problems("a.c", b"int x;\n"), "plain C passes")
    bios = BIOS_RESET + b"\0" * (BIOS_SIZE - 4)
    expect(bios_problem(bios), "BIOS reset vector"); expect(bios_problem(b"\1" * 100 + b"System ROM Version" + b"\1" * (BIOS_SIZE - 118)), "BIOS marker at 512 KiB")
    expect(bios_problem(b"Sony Computer Entertainment System ROM Version" + b"\1" * 70000), "BIOS strings in a large file")
    expect(not bios_problem(b"\1" * BIOS_SIZE) and not bios_problem(b"hello"), "random 512 KiB passes")
    for p in ("C:\\%s\\bob\\x" % u, "c:/%s/bob/x" % u, "/c/%s/bob/x" % u, "/%s/bob/x" % u, "/%s/bob/x" % hm, "D:\\\\%s\\\\bob" % u):
        expect(text_problems("see " + p), "home path " + p)
    for p in ("C:\\%s\\<home>\\x" % u, "C:\\%s\\Public" % u, "/%s/runner/work" % hm, "usr/%s/bob" % hm, "tools/%s/bob" % u):
        expect(not text_problems("see " + p), "allowed " + p)
    expect(text_problems("me" + at + "example.com") and not text_problems("1+x" + at + "users.noreply.github.com"), "e-mail")
    expect(identity_problems("a", "ZacheerKour", "344188240+ZacheerKour@users.noreply.github.com") == [] and identity_problems("a", "Bob", "bob" + at + "x.com"), "identity")
    # history: a temp repo with one good and one bad commit
    with tempfile.TemporaryDirectory() as d:
        env = dict(os.environ, GIT_AUTHOR_NAME="ZacheerKour", GIT_COMMITTER_NAME="ZacheerKour", GIT_AUTHOR_EMAIL="zacheerkour@users.noreply.github.com",
                   GIT_COMMITTER_EMAIL="zacheerkour@users.noreply.github.com")
        def g(*a, e=env): subprocess.check_call(["git", "-C", d, "-c", "commit.gpgsign=false"] + list(a), env=e, stdout=subprocess.DEVNULL)
        g("init", "-q"); open(os.path.join(d, "a.txt"), "w").write("ok\n"); g("add", "."); g("commit", "-qm", "good")
        expect(not history_problems(d, "HEAD"), "history: good commit passes")
        open(os.path.join(d, "a.txt"), "w").write("p = /" + hm + "/bob/x\n"); open(os.path.join(d, "b.zip"), "w").write("z")
        open(os.path.join(d, "c.dat"), "wb").write(bios)
        g("add", "."); g("commit", "-qm", "bad", e=dict(env, GIT_AUTHOR_EMAIL="bob" + at + "example.com", GIT_AUTHOR_NAME="Bob"))
        why = " | ".join(w for _, w in history_problems(d, "HEAD~1..HEAD"))
        for k in ("author e-mail", "author name", "added line: home path", "b.zip", "c.dat"): expect(k in why, "history catches " + k)
        expect(not history_problems(d, "HEAD~1"), "history range excludes the bad commit")
    print("repo_guard selftest: %d problem(s)" % n)
    return n


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if "--selftest" in sys.argv: sys.exit(1 if selftest() else 0)
    if "--history" in sys.argv:
        i = sys.argv.index("--history"); rng = sys.argv[i + 1] if i + 1 < len(sys.argv) else "HEAD"
        bad = history_problems(root, rng)
        for c, why in bad: print("FAIL", c, why)
        print("repo_guard --history %s: %d commit(s) checked, %d problem(s)" % (rng, len(git(root, "rev-list", rng).split()), len(bad)))
        sys.exit(1 if bad else 0)
    files, bad = tree_problems(root)
    for f, why in bad: print("FAIL", f, why)
    print("repo_guard: %d file(s) checked, %d problem(s)" % (len(files), len(bad)))
    sys.exit(1 if bad else 0)
